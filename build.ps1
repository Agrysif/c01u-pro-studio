# Builds everything with MSVC (Visual Studio 2019/2022 or Build Tools, "Desktop development with C++").
#   .\build.ps1            -> APO dll + app exe (with web UI and dll embedded) into .\dist
#   .\build.ps1 tests      -> DSP tests and APO host test into .\build, then runs them
#   .\build.ps1 all        -> both
param([string]$Target = "release")
$ErrorActionPreference = "Stop"
$Root = $PSScriptRoot
$Build = Join-Path $Root "build"
$Dist = Join-Path $Root "dist"
New-Item -ItemType Directory -Force -Path $Build, $Dist | Out-Null

function Import-VcVars {
  if (Get-Command cl.exe -ErrorAction SilentlyContinue) { return }
  $vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
  if (-not (Test-Path $vswhere)) { throw "Visual Studio / Build Tools not found" }
  $vs = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
  if (-not $vs) { throw "MSVC x64 toolset not found" }
  $bat = Join-Path $vs "VC\Auxiliary\Build\vcvars64.bat"
  $envDump = cmd /c "`"$bat`" >nul 2>&1 && set"
  foreach ($line in $envDump) {
    if ($line -match '^([^=]+)=(.*)$') { Set-Item -Path "env:$($matches[1])" -Value $matches[2] }
  }
}

function Invoke-Tool([string]$exe, [string[]]$arguments) {
  & $exe @arguments 2>&1 | ForEach-Object { Write-Host $_ }
  if ($LASTEXITCODE -ne 0) { throw "$exe failed with exit code $LASTEXITCODE" }
}

# WebView2 SDK (Microsoft, nuget.org): the panel window draws the web UI with the WebView2 runtime that
# ships with Windows 10/11. Downloaded once into .\deps and checked against a pinned SHA-256.
$WebView2Version = "1.0.4258.31"
$WebView2Sha256 = "56F7F4B8BF9AEE4B8EFEFBBDD4F67D5F74EBD1B100ED0806DA71BF76AF481AA9"
function Get-WebView2Sdk {
  $dir = Join-Path $Root "deps\webview2"
  if (Test-Path (Join-Path $dir "build\native\include\WebView2.h")) { return $dir }
  $deps = Join-Path $Root "deps"
  New-Item -ItemType Directory -Force -Path $deps | Out-Null
  $pkg = Join-Path $deps "microsoft.web.webview2.$WebView2Version.nupkg"
  if (-not (Test-Path $pkg)) {
    Write-Host "== downloading WebView2 SDK $WebView2Version" -ForegroundColor Cyan
    Invoke-WebRequest -UseBasicParsing -OutFile $pkg `
      "https://api.nuget.org/v3-flatcontainer/microsoft.web.webview2/$WebView2Version/microsoft.web.webview2.$WebView2Version.nupkg"
  }
  if ((Get-FileHash -Algorithm SHA256 $pkg).Hash -ne $WebView2Sha256) {
    Remove-Item $pkg
    throw "WebView2 SDK package checksum mismatch"
  }
  Expand-Archive -Path $pkg -DestinationPath $dir -Force
  return $dir
}

$CommonFlags = @("/nologo", "/O2", "/W3", "/EHsc", "/std:c++17", "/utf-8", "/MT", "/GS", "/Gy", "/Zi",
  "/DUNICODE", "/D_UNICODE", "/DWIN32_LEAN_AND_MEAN", "/DNOMINMAX", "/D_WIN32_WINNT=0x0602", "/DWINVER=0x0602",
  "/D_CRT_SECURE_NO_WARNINGS")

function Build-Tests {
  Write-Host "== dsp_test" -ForegroundColor Cyan
  Invoke-Tool cl.exe ($CommonFlags + @("/Fo$Build\\", "/Fd$Build\\dsp_test.pdb", "/Fe$Build\dsp_test.exe", "$Root\tests\dsp_test.cpp"))
  Write-Host "== update_test" -ForegroundColor Cyan
  $obj = Join-Path $Build "update_test"
  New-Item -ItemType Directory -Force -Path $obj | Out-Null
  Invoke-Tool cl.exe ($CommonFlags + @("/Fo$obj\\", "/Fd$obj\\update_test.pdb", "/Fe$Build\update_test.exe",
      "$Root\tests\update_test.cpp", "$Root\src\app\update_core.cpp", "/link", "winhttp.lib", "bcrypt.lib"))
}

function Build-Apo {
  Write-Host "== APO dll" -ForegroundColor Cyan
  $obj = Join-Path $Build "apo"
  New-Item -ItemType Directory -Force -Path $obj | Out-Null
  Invoke-Tool rc.exe @("/nologo", "/fo$obj\apo.res", "$Root\src\apo\apo.rc")
  Invoke-Tool cl.exe ($CommonFlags + @("/LD", "/Fo$obj\\", "/Fd$obj\\apo.pdb", "/Fe$Build\C01UProStudioApo.dll",
      "$Root\src\apo\apo.cpp", "$obj\apo.res", "/link", "/DEF:$Root\src\apo\apo.def", "/DEBUG", "/OPT:REF", "/OPT:ICF",
      "ole32.lib", "advapi32.lib", "uuid.lib", "user32.lib"))
}

function Build-ApoHostTest {
  Write-Host "== apo_host_test" -ForegroundColor Cyan
  Invoke-Tool cl.exe ($CommonFlags + @("/Fo$Build\\", "/Fd$Build\\apo_host_test.pdb", "/Fe$Build\apo_host_test.exe",
      "$Root\tests\apo_host_test.cpp", "/link", "ole32.lib", "uuid.lib", "propsys.lib"))
}

function Write-WebRc {
  # Every file under .\web becomes an RCDATA resource: web/i18n/ru.json -> WEB_I18N_RU_JSON
  # (names must stay unquoted, rc.exe keeps quotes as part of the name)
  $rc = Join-Path $Build "web.rc"
  $lines = @("// generated by build.ps1")
  Get-ChildItem -Path (Join-Path $Root "web") -Recurse -File | ForEach-Object {
    $rel = $_.FullName.Substring((Join-Path $Root "web").Length + 1)
    $name = "WEB_" + ($rel.ToUpper() -replace '[^A-Z0-9]', '_')
    $path = $_.FullName.Replace('\', '\\')
    $lines += "$name RCDATA `"$path`""
  }
  $lines += "APO_DLL RCDATA `"$((Join-Path $Build 'C01UProStudioApo.dll').Replace('\', '\\'))`""
  [IO.File]::WriteAllLines($rc, $lines, [Text.UTF8Encoding]::new($false))
  return $rc
}

function Build-App {
  Write-Host "== app exe" -ForegroundColor Cyan
  $obj = Join-Path $Build "app"
  New-Item -ItemType Directory -Force -Path $obj | Out-Null
  $webRc = Write-WebRc
  Invoke-Tool rc.exe @("/nologo", "/c65001", "/fo$obj\web.res", $webRc)
  Invoke-Tool rc.exe @("/nologo", "/c65001", "/I$Root\src", "/fo$obj\app.res", "$Root\src\app\app.rc")
  $sources = Get-ChildItem "$Root\src\app\*.cpp" | ForEach-Object { $_.FullName }
  $wv2 = Join-Path (Get-WebView2Sdk) "build\native"
  Invoke-Tool cl.exe ($CommonFlags + @("/I$wv2\include", "/Fo$obj\\", "/Fd$obj\\app.pdb", "/Fe$Build\C01UProStudio.exe") + $sources +
    @("$obj\app.res", "$obj\web.res", "/link", "/SUBSYSTEM:WINDOWS", "/DEBUG", "/OPT:REF", "/OPT:ICF",
      "$wv2\x64\WebView2LoaderStatic.lib", "dwmapi.lib", "version.lib",
      "ole32.lib", "oleaut32.lib", "uuid.lib", "user32.lib", "shell32.lib", "advapi32.lib", "ws2_32.lib",
      "gdi32.lib", "comctl32.lib", "propsys.lib", "setupapi.lib", "shlwapi.lib", "winmm.lib", "avrt.lib",
      "winhttp.lib", "bcrypt.lib", "taskschd.lib"))
}

Import-VcVars
switch ($Target) {
  "tests" {
    Build-Tests
    & "$Build\dsp_test.exe"
    if ($LASTEXITCODE -ne 0) { throw "dsp_test failed" }
    & "$Build\update_test.exe"
    if ($LASTEXITCODE -ne 0) { throw "update_test failed" }
    if (Test-Path "$Root\src\apo\apo.cpp") {
      Build-Apo
      Build-ApoHostTest
      & "$Build\apo_host_test.exe" "$Build\C01UProStudioApo.dll"
      if ($LASTEXITCODE -ne 0) { throw "apo_host_test failed" }
    }
  }
  "release" {
    Build-Apo
    Build-App
    Copy-Item "$Build\C01UProStudio.exe" $Dist -Force
    Write-Host "Done: $Dist\C01UProStudio.exe" -ForegroundColor Green
  }
  "all" {
    & $PSCommandPath tests
    & $PSCommandPath release
  }
  default { throw "unknown target $Target" }
}
